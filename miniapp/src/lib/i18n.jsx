export const I18nContext = createContext({ lang: 'uz', t: dict.uz, setLang: () => {} });

export function getDict(lang) {
  return dict[lang === 'ru' ? 'ru' : 'uz'];
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  const pick = (obj, field) => (ctx.lang === 'ru' && obj?.[field + 'Ru'] ? obj[field + 'Ru'] : obj?.[field]);
  const label = (item) => (item ? item[ctx.lang] || item.uz : '');
  return { ...ctx, pick, label };
}
